#!/usr/bin/env python3
"""Build or refresh authoring/queue.md from the Starlight sidebar in astro.config.mjs.

Generation order (deliberate): inside each chapter, topic pages first, then the
Chapter Overview; inside each part, all chapters first, then the Part Overview.
Overviews are written after the pages they summarize so they can link to real content.

Existing statuses in queue.md are preserved, so the script is safe to re-run after
the sidebar changes. New slugs are added as `todo`; removed slugs are dropped.

Usage: python3 authoring/build_queue.py [path/to/astro.config.mjs] [path/to/queue.md]
"""
import re
import sys
from pathlib import Path

CONFIG = Path(sys.argv[1] if len(sys.argv) > 1 else "astro.config.mjs")
QUEUE = Path(sys.argv[2] if len(sys.argv) > 2 else "authoring/queue.md")

STR = r"""'((?:[^'\\]|\\.)*)'|"((?:[^"\\]|\\.)*)\""""
TOKEN = re.compile(r"(label|tr|slug):\s*(?:" + STR + r")")


def unescape(s):
    return re.sub(r"\\(.)", r"\1", s)


def parse(text):
    sidebar = text[text.index("sidebar:"):]
    tokens = [(m.group(1), unescape(m.group(2) if m.group(2) is not None else m.group(3)))
              for m in TOKEN.finditer(sidebar)]
    entries, part, chapter = [], None, None
    pending = {}
    for kind, value in tokens:
        if kind == "label":
            pending = {"label": value}
        elif kind == "tr":
            pending["tr"] = value
        elif kind == "slug":
            label = pending.get("label", "")
            if label == "Part Overview":
                typ = "part-overview"
            elif label == "Chapter Overview":
                typ = "chapter-overview"
            else:
                typ = "topic"
            # Entries outside the numbered parts (e.g. "What's New") are site pages
            # maintained by scripts, not handbook pages to generate.
            if part is not None:
                entries.append({"type": typ, "slug": value, "label": label,
                                "tr": pending.get("tr", ""), "part": part, "chapter": chapter})
            pending = {}
            continue
        # group headers carry label + tr but no slug
        if kind == "tr" and "label" in pending:
            label = pending["label"]
            if re.match(r"^[IVXLC]+\. ", label):
                part, chapter = (label, pending["tr"]), None
            elif re.match(r"^\d+\.\d+\. ", label):
                chapter = (label, pending["tr"])
    return entries


def order(entries):
    out, part_ov, chap_ov, chap_topics = [], None, None, []

    def flush_chapter():
        nonlocal chap_ov, chap_topics
        out.extend(chap_topics)
        if chap_ov:
            out.append(chap_ov)
        chap_ov, chap_topics = None, []

    for e in entries:
        if e["type"] == "part-overview":
            flush_chapter()
            if part_ov:
                out.append(part_ov)
            part_ov = e
        elif e["type"] == "chapter-overview":
            flush_chapter()
            chap_ov = e
        else:
            chap_topics.append(e)
    flush_chapter()
    if part_ov:
        out.append(part_ov)
    return out


def load_statuses():
    """Return slug -> (status, depth, note). Reads both the old 6-column layout
    (# | Status | Type | Slug | Title | Note) and the 7-column layout with Depth."""
    statuses = {}
    if QUEUE.exists():
        for line in QUEUE.read_text(encoding="utf-8").splitlines():
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if len(cells) == 7 and cells[0].isdigit():
                statuses[cells[4].strip("`")] = (cells[1], cells[3], cells[6])
            elif len(cells) == 6 and cells[0].isdigit():
                statuses[cells[3].strip("`")] = (cells[1], "-", cells[5])
    return statuses


def main():
    entries = order(parse(CONFIG.read_text(encoding="utf-8")))
    slugs = [e["slug"] for e in entries]
    assert len(slugs) == len(set(slugs)), "duplicate slugs in sidebar"
    statuses = load_statuses()
    rows = []
    for i, e in enumerate(entries, 1):
        status, depth, note = statuses.get(e["slug"], ("todo", "-", ""))
        title = re.sub(r"^\d+(\.\d+)*\.\s*", "", e["label"])
        if e["type"] == "chapter-overview":
            title = re.sub(r"^\d+\.\d+\.\s*", "", e["chapter"][0])
        elif e["type"] == "part-overview":
            title = re.sub(r"^[IVXLC]+\.\s*", "", e["part"][0])
        rows.append(f"| {i:03d} | {status} | {e['type']} | {depth} | `{e['slug']}` | {title} | {note} |")
    done = sum(1 for r in rows if "| done |" in r)
    header = (
        "# Generation Queue\n\n"
        "Generated by `authoring/build_queue.py` from the sidebar in `astro.config.mjs`.\n"
        "Status values: `todo`, `done`, `failed`. Set a row back to `todo` to regenerate it.\n"
        "Depth is chosen by each run for topic pages (`standard` or `deep`, see\n"
        "project-instruction.md section 2.1); `-` means not yet generated or not a topic page.\n"
        "Each scheduled run takes the first `todo` row from the top.\n\n"
        f"Progress: {done} / {len(rows)} done.\n\n"
        "| # | Status | Type | Depth | Slug | Title | Note |\n"
        "|---|---|---|---|---|---|---|\n"
    )
    QUEUE.write_text(header + "\n".join(rows) + "\n", encoding="utf-8")
    kinds = {t: sum(1 for e in entries if e["type"] == t) for t in ("topic", "chapter-overview", "part-overview")}
    print(f"{len(rows)} entries {kinds}, {done} done -> {QUEUE}")


if __name__ == "__main__":
    main()
