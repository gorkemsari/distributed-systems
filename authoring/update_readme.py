#!/usr/bin/env python3
"""Regenerate the Roadmap & Progress Tracker in README.md.

The tracker is rebuilt from two sources of truth, so it can never drift:
  - the sidebar in astro.config.mjs (structure, order, labels), parsed with
    the same function as build_queue.py;
  - authoring/queue.md (a page counts as published when its status is `done`).

Only the text between the ROADMAP markers in README.md is replaced; the rest
of the README is left untouched. Running the script twice gives the same file.

Usage: python3 authoring/update_readme.py [astro.config.mjs] [authoring/queue.md] [README.md]
"""
import importlib.util
import re
import sys
from pathlib import Path

CONFIG = Path(sys.argv[1] if len(sys.argv) > 1 else "astro.config.mjs")
QUEUE = Path(sys.argv[2] if len(sys.argv) > 2 else "authoring/queue.md")
README = Path(sys.argv[3] if len(sys.argv) > 3 else "README.md")
START = "<!-- ROADMAP:START (generated by authoring/update_readme.py, do not edit by hand) -->"
END = "<!-- ROADMAP:END -->"
SITE = "https://gorkemsari.github.io/distributed-systems"


sys.dont_write_bytecode = True  # importing build_queue must not leave __pycache__ behind


def load_parser():
    spec = importlib.util.spec_from_file_location(
        "build_queue", Path(__file__).with_name("build_queue.py"))
    mod = importlib.util.module_from_spec(spec)
    argv, sys.argv = sys.argv, sys.argv[:1]  # build_queue reads argv at import
    try:
        spec.loader.exec_module(mod)
    finally:
        sys.argv = argv
    return mod.parse


def load_status():
    status = {}
    for line in QUEUE.read_text(encoding="utf-8").splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if cells and cells[0].isdigit():
            slug_cell = cells[4] if len(cells) == 7 else cells[3]
            status[slug_cell.strip("`")] = cells[1]
    return status


def box(done):
    return "[x]" if done else "[ ]"


def link(label, slug, done):
    # Published pages link to the live site; unpublished ones stay plain text.
    return f"[{label}]({SITE}/en/{slug}/)" if done else label


def render(entries, status):
    parts = []  # [(part_label, part_overview_entry, [(chapter_label, [entries])])]
    for e in entries:
        part_label = e["part"][0] if e["part"] else ""
        if not parts or parts[-1][0] != part_label:
            parts.append([part_label, None, []])
        part = parts[-1]
        if e["type"] == "part-overview":
            part[1] = e
            continue
        chapter_label = e["chapter"][0] if e["chapter"] else ""
        if not part[2] or part[2][-1][0] != chapter_label:
            part[2].append([chapter_label, []])
        part[2][-1][1].append(e)

    def is_done(e):
        return status.get(e["slug"]) == "done"

    total = len(entries)
    done = sum(is_done(e) for e in entries)
    pct = round(100 * done / total) if total else 0

    out = [
        f"**Progress:** {done} of {total} pages published ({pct}%). "
        "Each page is published in English and Turkish; overview pages are counted.",
        "",
    ]
    for label, overview, chapters in parts:
        items = ([overview] if overview else []) + [e for _, es in chapters for e in es]
        n_done = sum(is_done(e) for e in items)
        m = re.match(r"^([IVXLC]+)\.\s*(.*)$", label)
        name = f"**{m.group(1)}.** {m.group(2)}" if m else f"**{label}**"
        out.append(f"- {box(n_done == len(items))} {name} ({n_done}/{len(items)})")
    out += ["", "<details>",
            "<summary><b>📂 Click here to expand the detailed chapter checklist</b></summary>",
            "<br>", ""]
    for i, (label, overview, chapters) in enumerate(parts):
        out.append(f"### {label}")
        if overview:
            out.append(f"- {box(is_done(overview))} {link('Part Overview', overview['slug'], is_done(overview))}")
        for chapter_label, es in chapters:
            out += ["", f"**{chapter_label}**"]
            for e in es:
                text = "Chapter Overview" if e["type"] == "chapter-overview" else e["label"]
                out.append(f"- {box(is_done(e))} {link(text, e['slug'], is_done(e))}")
        out += ["", "---", ""] if i < len(parts) - 1 else [""]
    out.append("</details>")
    return "\n".join(out), done, total


def main():
    parse = load_parser()
    entries = parse(CONFIG.read_text(encoding="utf-8"))
    body, done, total = render(entries, load_status())
    text = README.read_text(encoding="utf-8")
    if START not in text or END not in text:
        sys.exit(f"README markers not found: {START} ... {END}")
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    README.write_text(f"{head}{START}\n{body}\n{END}{tail}", encoding="utf-8")
    print(f"README tracker: {done}/{total} published")


if __name__ == "__main__":
    main()
